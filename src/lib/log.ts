// Безопасное текстовое представление ошибки для логов.
// Пишем только message/строку, а не полный объект ошибки: у внешних библиотек
// (nodemailer, http-клиенты) он может тянуть за собой конфиг подключения,
// заголовки и прочие детали, которые не должны попадать в логи контейнера.
export function errText(err: unknown): string {
  return err instanceof Error ? err.message : String(err);
}
